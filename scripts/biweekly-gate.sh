#!/usr/bin/env bash
#
# 주 1회 크론을 격주로 낮춘다. GitHub Actions 크론은 "2주마다"를 직접
# 지원하지 않아서, 매주 그대로 트리거되게 두고 잡 맨 앞에서 이번이
# 실행 주인지만 스스로 판단한다 — 아니면 뒤 스텝을 건너뛴다(3초짜리
# 판정 스텝만 돈다).
#
# 2026-09월 GitHub Actions 무료 한도(월 2,000분) 소진의 계기가 된
# weekly-discover(신규 발굴)부터 이걸로 격주 전환했다(2026-09-28).
#
# 기준일(EPOCH)로부터 지난 일수를 7로 나눈 몫의 홀짝으로 "실행 주"를
# 가른다. 요일이 도메인마다 다르므로(카페 일·식당 월·가볼곳 화) 달력 주
# (ISO week, 월요일에 바뀜) 대신 이 방식을 쓴다 — ISO 주를 그대로 쓰면
# 일요일(카페)과 그다음 날인 월·화요일(식당·가볼곳)이 매번 다른 주로
# 갈라진다.
#
# 기준일은 **수요일**이어야 한다 — 그래야 7일 구간이 수~화로 떨어져
# 일·월·화(카페·식당·가볼곳 실행일) 사흘이 항상 같은 구간 끝에 붙는다.
# 세 워크플로가 같은 기준일을 쓰면 셋이 같은 2주 주기로 맞물린다.
set -euo pipefail

EPOCH='2026-01-07'
days=$(( ( $(date -u +%s) - $(date -u -d "$EPOCH" +%s) ) / 86400 ))

if [ $(( (days / 7) % 2 )) -eq 0 ]; then
  echo "run=true" >> "$GITHUB_OUTPUT"
else
  echo "run=false" >> "$GITHUB_OUTPUT"
  echo "격주 휴식 주 — 이번 주는 건너뜁니다 (2주에 한 번만 실행)"
fi
