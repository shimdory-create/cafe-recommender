/**
 * 열람 전용 배포.
 *
 * 같은 코드를 Vercel 프로젝트 두 개로 띄운다. 하나는 가족용(쓰기 가능),
 * 하나는 동료에게 주는 열람용이다. 열람용은 두 겹으로 막는다:
 *
 *   1. `NEXT_PUBLIC_VIEW_ONLY=1`  — 입력 UI 를 감추고 쓰기 API 를 403 으로 막는다
 *   2. **읽기 전용 GitHub 토큰**   — 코드에 구멍이 있어도 GitHub 이 거절한다
 *
 * 1번만 두면 개발자도구로 뚫린다. 2번이 실제 방어선이고 1번은 화면을
 * 정직하게 만드는 쪽이다.
 *
 * `NEXT_PUBLIC_` 접두사라 빌드 시점에 값이 박힌다 — 서버·클라이언트가 같은
 * 값을 보므로 화면이 한 번 깜빡이며 버튼이 사라지는 일이 없다.
 */
